"""在「从这些错误里提炼的方法」一节补入 E16~E20 的教训。"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
p = os.path.join(ROOT, "第2次评审测试", "过程记录", "AI出错与修正记录.md")
t = open(p, encoding="utf-8").read()

old = """| 同一错误要全局搜一遍 | E05 一个解包错误在 4 处同时存在，只改一处会再犯 |"""
new = """| 同一错误要全局搜一遍 | E05 一个解包错误在 4 处同时存在，只改一处会再犯 |
| **主题变了，要回头检查所有相关文档** | 不能只改"主文件"；汇报稿因没跟着更新，整篇讲成了上轮内容（E16） |
| **批量替换后必须看结果** | 全局替换会误伤目录树这类结构化内容，跑完要打印出来看一眼（E17） |
| **合并 = 改文件 + 改引用 + 改数字** | 三件事必须同时做，否则会留下"21 项""112 条"这类幽灵数字（E18） |
| **合并前先确认内容是否仍有效** | 按文件名判断"都是手动指南"差点把已作废的口令码流程合进来（E19） |
| **写用例前先把被测代码读全** | 边写边发现会漏点；手动用例首版就漏了前后端密码规则不一致两项（E20） |"""
assert old in t
t = t.replace(old, new, 1)
open(p, "w", encoding="utf-8").write(t)
print("方法论已补入 5 条教训")
