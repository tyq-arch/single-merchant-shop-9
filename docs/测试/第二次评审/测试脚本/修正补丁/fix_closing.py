"""更新结尾「给评审的一句话」，使之与 20 处错误分类一致。"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
p = os.path.join(ROOT, "第2次评审测试", "过程记录", "AI出错与修正记录.md")
t = open(p, encoding="utf-8").read()

old = ('> "这份材料是 AI 辅助整理的，过程中一共出现 20 处错误，我全部记录在本文件里。'
       '其中 2 处影响了测试结论——一是我把 `12345` 的提示文案写错、二是我把一条用例的预期写反产生了假失败，'
       '这两处都是我自己复核时发现并修正的，修正过程和验证结果都在上面。'
       '**没有修的、会影响结论的错误，一处都没有。**"')

new = ('''> "这份材料是 AI 辅助整理的，过程中一共出现 **20 处错误**，我全部记录在本文件里，包括每处的原始报错、根因、怎么发现、怎么修、怎么验证。
>
> 其中有 **2 处影响了测试结论**——一是我把 `12345` 的提示文案写错、二是我把一条用例的预期写反产生了假失败，这两处都是我自己复核时发现的，已修正并重新出数。
>
> 另有 **3 处影响了材料内容或覆盖范围**——汇报稿一度写成上一轮的内容、差点把已作废的旧指南原样合并、手动用例漏了 2 项，也都在发现后修正或拦截了。
>
> **没有修的、会影响结论的错误，一处都没有。**"''')

assert old in t, "未找到结尾语句"
t = t.replace(old, new, 1)
open(p, "w", encoding="utf-8").write(t)
print("结尾语句已更新")
